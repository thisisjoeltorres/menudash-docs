-- PostgreSQL local. Solo estructura relacional: sin triggers, funciones ni RLS.
CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  rol VARCHAR(20) NOT NULL UNIQUE CHECK (rol IN ('mostrador','cocina','admin')),
  pin VARCHAR(20) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS menu (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL CHECK (length(trim(nombre)) > 0),
  precio INTEGER NOT NULL CHECK (precio >= 0),
  emo VARCHAR(16) NOT NULL DEFAULT '🍽️',
  tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('hamburguesa','plato','bebida')),
  eliminado BOOLEAN NOT NULL DEFAULT FALSE,
  actualizado TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turno INTEGER NOT NULL,
  destino VARCHAR(120) NOT NULL CHECK (length(trim(destino)) > 0),
  total INTEGER NOT NULL DEFAULT 0 CHECK (total >= 0),
  estado VARCHAR(20) NOT NULL DEFAULT 'cocinando' CHECK (estado IN ('cocinando','listo','entregado','cancelado')),
  creado TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS items_pedido (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
  id_prod BIGINT REFERENCES menu(id) ON DELETE SET NULL,
  nombre VARCHAR(120) NOT NULL,
  precio INTEGER NOT NULL CHECK (precio >= 0),
  cant INTEGER NOT NULL CHECK (cant > 0),
  notas TEXT[] NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_pedidos_estado ON pedidos(estado);
CREATE INDEX IF NOT EXISTS idx_pedidos_creado ON pedidos(creado DESC);
CREATE INDEX IF NOT EXISTS idx_items_pedido ON items_pedido(pedido_id);
